"""Evaluation scorecards, sub-metrics, security findings, and report models."""

import uuid
from datetime import UTC, datetime
from decimal import Decimal
from typing import TYPE_CHECKING, Any

from sqlalchemy import (
    Boolean,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, UUIDPrimaryKeyMixin

if TYPE_CHECKING:
    from app.models.test_run import TestExecution, TestRun


class Evaluation(Base, UUIDPrimaryKeyMixin):
    """Graded assessment generated by an evaluator for a test execution.

    Records comprehensive metadata to ensure complete evaluation reproducibility
    and auditing across model revisions.
    """

    __tablename__ = "evaluations"
    __table_args__ = (
        Index("ix_evaluations_execution", "test_execution_id"),
        Index("ix_evaluations_name", "evaluator_name"),
    )

    test_execution_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("test_executions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        doc="Foreign key reference to evaluated test execution",
    )
    evaluator_type: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        doc="Evaluator category: DETERMINISTIC, LLM_JUDGE, or SECURITY",
    )
    evaluator_name: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        doc="Unique evaluator identifier (e.g., tool_schema_validator, groundedness_judge)",
    )
    evaluator_version: Mapped[str] = mapped_column(
        String(50),
        default="1.0.0",
        nullable=False,
        doc="Semantic code version of the evaluator engine",
    )
    rubric_version: Mapped[str] = mapped_column(
        String(50),
        default="v1.0",
        nullable=False,
        doc="Version of evaluation rubric and grading criteria applied",
    )
    llm_provider: Mapped[str | None] = mapped_column(
        String(50),
        nullable=True,
        doc="AI provider used for judge (openai, anthropic, gemini; null for deterministic)",
    )
    llm_model: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        doc="Explicitly pinned model snapshot ID (e.g., gpt-4o-2024-08-06)",
    )
    generation_parameters: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        default=dict,
        nullable=False,
        doc="Sampling settings: {'temperature': 0.0, 'seed': 42, 'max_tokens': 1200}",
    )
    passed: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        doc="Whether this evaluation criteria passed or failed",
    )
    score: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        doc="Normalized evaluation score between 0.0 and 1.0",
    )
    confidence: Mapped[float] = mapped_column(
        Float,
        default=1.0,
        nullable=False,
        doc="Evaluator confidence score between 0.0 and 1.0",
    )
    reasoning: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        doc="Structured explanatory verdict rationale (private CoT is never stored)",
    )
    structured_evidence: Mapped[list[dict[str, Any]]] = mapped_column(
        JSONB,
        default=list,
        nullable=False,
        doc="Array of verifiable citation objects linking directly to trace event indices",
    )
    execution_latency_ms: Mapped[int] = mapped_column(
        Integer,
        default=0,
        nullable=False,
        doc="Duration taken by the evaluator in milliseconds",
    )
    token_usage: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        default=dict,
        nullable=False,
        doc="Judge tokens consumed: {'prompt_tokens': 850, 'completion_tokens': 120}",
    )
    estimated_cost_usd: Mapped[Decimal] = mapped_column(
        Numeric(10, 6),
        default=Decimal("0.000000"),
        nullable=False,
        doc="Calculated USD cost of the evaluation inference call",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        server_default=func.now(),
        nullable=False,
        doc="Timestamp of evaluation record generation (UTC)",
    )

    # Relationships
    test_execution: Mapped["TestExecution"] = relationship(back_populates="evaluations")
    metrics: Mapped[list["EvaluationMetric"]] = relationship(
        back_populates="evaluation",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )


class EvaluationMetric(Base, UUIDPrimaryKeyMixin):
    """Sub-metric score breakdown supporting a parent evaluation."""

    __tablename__ = "evaluation_metrics"

    evaluation_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("evaluations.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        doc="Foreign key reference to parent evaluation record",
    )
    metric_name: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        doc="Discrete sub-metric name (e.g., argument_type_match, latency_budget)",
    )
    score: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        doc="Numerical score achieved for this sub-metric",
    )
    threshold: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        doc="Minimum threshold required for this sub-metric to pass",
    )
    passed: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        doc="Whether this specific sub-metric passed threshold",
    )
    details: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        default=dict,
        nullable=False,
        doc="Additional diagnostic context or calculation metadata",
    )

    # Relationships
    evaluation: Mapped["Evaluation"] = relationship(back_populates="metrics")


class SecurityFinding(Base, UUIDPrimaryKeyMixin):
    """Vulnerability or safety finding uncovered during adversarial testing."""

    __tablename__ = "security_findings"

    test_execution_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("test_executions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        doc="Foreign key reference to test execution uncovering this finding",
    )
    severity: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        doc="Severity: CRITICAL, HIGH, MEDIUM, LOW, or INFO",
    )
    vulnerability_type: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        doc="Vulnerability class: DIRECT_PROMPT_INJECTION, UNAUTHORIZED_TOOL_INVOCATION, etc.",
    )
    description: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        doc="Detailed explanation of how the vulnerability manifested",
    )
    remediation: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        doc="Actionable engineering advice to mitigate the security flaw",
    )
    raw_evidence: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        nullable=False,
        doc="Exact prompt injection payloads and agent response captures",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        server_default=func.now(),
        nullable=False,
        doc="Timestamp of finding creation (UTC)",
    )

    # Relationships
    test_execution: Mapped["TestExecution"] = relationship(
        back_populates="security_findings"
    )


class RegressionResult(Base, UUIDPrimaryKeyMixin):
    """Delta comparison between a base test run and a candidate test run."""

    __tablename__ = "regression_results"

    base_run_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("test_runs.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        doc="Foreign key reference to baseline test run",
    )
    candidate_run_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("test_runs.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        doc="Foreign key reference to new candidate test run",
    )
    newly_failed_count: Mapped[int] = mapped_column(
        Integer,
        default=0,
        nullable=False,
        doc="Number of test cases that passed in baseline but failed in candidate",
    )
    newly_passed_count: Mapped[int] = mapped_column(
        Integer,
        default=0,
        nullable=False,
        doc="Number of test cases that failed in baseline but passed in candidate",
    )
    summary: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        default=dict,
        nullable=False,
        doc="Detailed categorization of regressions and status flips",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        server_default=func.now(),
        nullable=False,
        doc="Timestamp when regression diff was calculated (UTC)",
    )


class Report(Base, UUIDPrimaryKeyMixin):
    """Exportable test execution summary and CI/CD quality gate report."""

    __tablename__ = "reports"

    test_run_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("test_runs.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        doc="Foreign key reference to summarized test run",
    )
    title: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
        doc="Report title (e.g., CI/CD Regression Gate #142 - Main Branch)",
    )
    report_format: Mapped[str] = mapped_column(
        String(50),
        default="JSON",
        nullable=False,
        doc="Export serialization format: JSON, MARKDOWN, or PDF",
    )
    content: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        nullable=False,
        doc="Complete structured report metrics and quality-gate sign-offs",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        server_default=func.now(),
        nullable=False,
        doc="Timestamp of report generation (UTC)",
    )

    # Relationships
    test_run: Mapped["TestRun"] = relationship(back_populates="reports")
